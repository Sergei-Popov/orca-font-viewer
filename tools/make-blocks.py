"""Writes src/font/blocks-data.ts from fontTools' copy of Unicode's Blocks.txt (fontTools 4.60.1
ships Blocks-16.0.0.txt; Unicode data is under the Unicode License v3).

    pip install --target /tmp/fontlib fonttools
    PYTHONPATH=/tmp/fontlib python3 tools/make-blocks.py
"""

import os

from fontTools.unicodedata import Blocks

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "font", "blocks-data.ts")

rows = []
for start, name in zip(Blocks.RANGES, Blocks.VALUES):
    # Gaps between blocks are kept as '' so a code point there is not given the previous block.
    rows.append(f"  [0x{start:X}, {('' if name == 'No_Block' else name)!r}],")

with open(OUT, "w", encoding="utf-8") as fh:
    fh.write("// Generated by tools/make-blocks.py from Unicode's Blocks.txt (via fontTools). Do not edit.\n")
    fh.write("// Each entry is [first code point, block name]; a block ends where the next one starts; '' is a gap.\n\n")
    fh.write("export const BLOCK_STARTS: readonly (readonly [number, string])[] = [\n")
    fh.write("\n".join(rows))
    fh.write("\n]\n")
print(len(rows), "blocks")
