#!/usr/bin/env node
// Writes vendor/brotli/dictionary.mjs: the Brotli static dictionary as a readable word list.
//
//   node tools/make-brotli-dictionary.mjs [dictionary.bin]
//
// Source: the static dictionary of RFC 7932 (Appendix A), as google/brotli ships it in
// c/common/dictionary.bin (tag v1.1.0, commit ed738e842d2fbdf2d6459e39267a633c4a9b2f5d):
// 122,784 bytes, sha256 20e42eb1b511c21806d4d227d07e5dd06877d8ce7b3a817f378f313653f35c70.
// Without an argument the file is downloaded from that commit; either way its sha256 must match.
//
// The dictionary is 13,504 words of 4 to 24 bytes: 2^sizeBits[length] words of each length, one
// after another. Each word is written as its UTF-8 text; the few words that are not valid UTF-8 on
// their own (a multi-byte character cut by the word's end) are written as arrays of byte values.
// src/font/brotli-dictionary.ts assembles the bytes again, and its test checks the sha256.

import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const SHA256 = '20e42eb1b511c21806d4d227d07e5dd06877d8ce7b3a817f378f313653f35c70'
const URL = 'https://raw.githubusercontent.com/google/brotli/ed738e842d2fbdf2d6459e39267a633c4a9b2f5d/c/common/dictionary.bin'
const SIZE_BITS = [0, 0, 0, 0, 10, 10, 11, 11, 10, 10, 10, 10, 10, 9, 9, 8, 7, 7, 8, 7, 7, 6, 6, 5, 5]
const LINE = 100

const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'vendor', 'brotli', 'dictionary.mjs')
const source = process.argv[2]
const bytes = source ? readFileSync(source) : Buffer.from(await (await fetch(URL)).arrayBuffer())
const sha = createHash('sha256').update(bytes).digest('hex')
if (bytes.length !== 122784 || sha !== SHA256) {
  throw new Error(`not the Brotli dictionary: ${bytes.length} bytes, sha256 ${sha}`)
}

const utf8 = new TextDecoder('utf-8', { fatal: true })
const lines = [
  '// Generated by tools/make-brotli-dictionary.mjs. Do not edit.',
  '//',
  '// The Brotli static dictionary of RFC 7932 (Appendix A), as google/brotli v1.1.0 ships it in',
  '// c/common/dictionary.bin: 122,784 bytes,',
  `// sha256 ${SHA256}.`,
  '// Its 13,504 words of 4 to 24 bytes are listed by length, each as its UTF-8 text, or as byte',
  '// values when it is not valid UTF-8 on its own.',
  '// src/font/brotli-dictionary.ts puts the bytes back together; its test checks the sha256.',
  '',
  'export const WORDS_BY_LENGTH = {'
]
let at = 0
let byteWords = 0
for (let length = 4; length <= 24; length++) {
  lines.push(`  ${length}: [`)
  let line = '   '
  for (let i = 0; i < 1 << SIZE_BITS[length]; i++) {
    const word = bytes.subarray(at, at + length)
    at += length
    let item
    try {
      item = JSON.stringify(utf8.decode(word))
    } catch {
      item = `[${[...word].join(', ')}]`
      byteWords++
    }
    if (line.length + 1 + item.length + 1 > LINE) {
      lines.push(line)
      line = '   '
    }
    line += ` ${item},`
  }
  lines.push(line, '  ],')
}
lines.push('}', '')
writeFileSync(out, lines.join('\n'))
const written = createHash('sha256').update(readFileSync(out)).digest('hex')
console.log(`${out}: ${at} bytes in 13,504 words (${byteWords} as byte values); file sha256 ${written}`)
