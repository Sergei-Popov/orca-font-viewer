"""Builds the tiny fonts the unit tests parse and writes them to src/font/test-fixtures.ts.

The fonts are drawn here (rectangles), so they carry no third-party licence. Needs fontTools
and brotli (for WOFF2):

    pip install --target /tmp/fontlib fonttools brotli
    PYTHONPATH=/tmp/fontlib python3 tools/make-fixtures.py
"""

import base64
import io
import os

from fontTools.feaLib.builder import addOpenTypeFeaturesFromString
from fontTools.fontBuilder import FontBuilder
from fontTools.misc.timeTools import timestampFromString
from fontTools.pens.t2CharStringPen import T2CharStringPen
from fontTools.pens.ttGlyphPen import TTGlyphPen
from fontTools.ttLib import TTFont
from fontTools.ttLib.ttCollection import TTCollection

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "src", "font", "test-fixtures.ts")

GLYPHS = [".notdef", "space", "A", "B", "f", "i", "f_i", "uni0411", "u1F600"]
CMAP = {0x20: "space", 0x41: "A", 0x42: "B", 0x66: "f", 0x69: "i", 0x411: "uni0411", 0x1F600: "u1F600"}
FEATURES = """
languagesystem DFLT dflt;
languagesystem latn dflt;
feature liga { sub f i by f_i; } liga;
feature ss01 { featureNames { name "Alternate A"; }; sub A by B; } ss01;
feature kern { pos A B -50; } kern;
"""


def rect(pen, x0, y0, x1, y1):
    pen.moveTo((x0, y0))
    pen.lineTo((x0, y1))
    pen.lineTo((x1, y1))
    pen.lineTo((x1, y0))
    pen.closePath()


def names(family, style):
    return {
        "familyName": {"en": family, "ru": "Тестовый"},
        "styleName": style,
        "uniqueFontIdentifier": f"fixture:{family}-{style}",
        "fullName": f"{family} {style}",
        "psName": f"{family.replace(' ', '')}-{style}",
        "version": "Version 1.002",
        "copyright": "Copyright 2026 Font Viewer tests",
        "designer": "Font Viewer",
        "designerURL": "https://example.com/designer",
        "licenseDescription": "Free to use in tests.",
        "licenseInfoURL": "https://example.com/license",
        "sampleText": "Fixture sample",
    }


def build(family="Fixture Sans", style="Regular", cff=False, variable=False):
    fb = FontBuilder(1000, isTTF=not cff)
    fb.setupGlyphOrder(GLYPHS)
    fb.setupCharacterMap(CMAP)
    advance = {g: 600 for g in GLYPHS}
    advance["space"] = 250
    if cff:
        charstrings = {}
        for g in GLYPHS:
            pen = T2CharStringPen(advance[g], None)
            if g != "space":
                rect(pen, 50, 0, 550, 700)
            charstrings[g] = pen.getCharString()
        fb.setupCFF(names(family, style)["psName"], {"FullName": f"{family} {style}"}, charstrings, {})
    else:
        glyphs = {}
        for g in GLYPHS:
            pen = TTGlyphPen(None)
            if g != "space":
                rect(pen, 50, 0, 550, 700)
            glyphs[g] = pen.glyph()
        fb.setupGlyf(glyphs)
    fb.setupHorizontalMetrics({g: (advance[g], 50) for g in GLYPHS})
    fb.setupHorizontalHeader(ascent=800, descent=-200)
    fb.setupNameTable(names(family, style))
    fb.setupOS2(
        usWeightClass=400,
        usWidthClass=5,
        fsType=0x0008,
        achVendID="TEST",
        sTypoAscender=800,
        sTypoDescender=-200,
        sxHeight=500,
        sCapHeight=700,
        version=4,
    )
    fb.setupPost(isFixedPitch=0, italicAngle=0)
    fb.setupHead(unitsPerEm=1000, fontRevision=1.002)
    stamp = timestampFromString("Mon Jan  5 12:00:00 2026")
    fb.font["head"].created = stamp
    fb.font["head"].modified = stamp
    if variable:
        fb.setupFvar(
            axes=[("wght", 100, 400, 900, "Weight"), ("wdth", 75, 100, 125, "Width")],
            instances=[
                {"location": {"wght": 700, "wdth": 100}, "stylename": "Bold"},
                {"location": {"wght": 100, "wdth": 75}, "stylename": "Thin Condensed"},
            ],
        )
    addOpenTypeFeaturesFromString(fb.font, FEATURES)
    return fb.font


def to_bytes(font, flavor=None):
    font.flavor = flavor
    buf = io.BytesIO()
    font.save(buf)
    return buf.getvalue()


def ttc_bytes():
    collection = TTCollection()
    collection.fonts = [build("Fixture Sans", "Regular"), build("Fixture Mono", "Bold")]
    buf = io.BytesIO()
    collection.save(buf)
    return buf.getvalue()


def main():
    fixtures = {
        "ttf": to_bytes(build(variable=True)),
        "otf": to_bytes(build(cff=True)),
        "woff": to_bytes(build(variable=True), "woff"),
        "woff2": to_bytes(build(variable=True), "woff2"),
        "ttc": ttc_bytes(),
    }
    lines = [
        "// Generated by tools/make-fixtures.py: tiny fonts drawn for the tests. Do not edit.",
        "",
        "const decode = (base64: string): Uint8Array => Uint8Array.from(atob(base64), (c) => c.charCodeAt(0))",
        "",
    ]
    for key, data in fixtures.items():
        lines.append(f"/** {len(data)} bytes. */")
        lines.append(f"export const {key}Fixture = decode('{base64.b64encode(data).decode()}')")
        lines.append("")
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print("wrote", OUT, {k: len(v) for k, v in fixtures.items()})


if __name__ == "__main__":
    main()
